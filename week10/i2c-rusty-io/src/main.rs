fn io_reset() {
    // Reset, then deassert the reset on IO_BANK0
    // See Section 2.14 in the datasheet for details
    set_bits(RESETS_BASE, 1 << 5); // Write 1 to reset
    clear_bits(RESETS_BASE, 1 << 5); // Write 0 to deassert reset

    // Reset, then deassert the reset on PADS_BANK0
    // See Section 2.14 in the datasheet for details
    set_bits(RESETS_BASE, 1 << 8); // Write 1 to reset
    clear_bits(RESETS_BASE, 1 << 8); // Write 0 to deassert reset
}

// I2C address of the compass
const ADDRESS: u8 = 0x0D;

// Register addresses
const REG_XOUT_LSB: u8 = 0x00;
const REG_STATUS: u8 = 0x06;
const REG_CR1: u8 = 0x09;
const REG_CR2: u8 = 0x0A;
const REG_SR_PERIOD: u8 = 0x0B;

/*
 * The actual main function.
 */
#[entry]
fn main() -> ! {
    // Initialize the clocks and IO pins
    sys_clock::init_clocks();
    io_reset();

    let sda = pin_io::get_pin(2).unwrap();
    let scl = pin_io::get_pin(3).unwrap();

    let my_i2c = I2C1::new(sda, scl);
    my_i2c.init();

    // Delay for a bit for everything to initialize
    for _ in 0..800000 {
        cortex_m::asm::nop();
    }

    // Initialize the I2C peripheral
    my_i2c.write(ADDRESS, REG_CR2, 0x80); // Reset the sensor
    my_i2c.write(ADDRESS, REG_SR_PERIOD, 0x01); // Set the period based on the datasheet
    my_i2c.write(ADDRESS, REG_CR1, 0x11); // Set the sensor in continuous mode (from the datasheet)

    loop {
        // Wait for the sensor to signal ready
        loop {
            let mut status = [0u8; 1];
            my_i2c.read(ADDRESS, REG_STATUS, &mut status);
            // If data is ready, break
            if (status[0] & 0x01) != 0 {
                break;
            }
            // Minor wait
            for _ in 0..8000 {
                cortex_m::asm::nop();
            }
        }

        // Read the X value
        let mut bytes = [0u8, 0u8];
        my_i2c.read(ADDRESS, REG_XOUT_LSB, &mut bytes);
        let x = (bytes[1] as i16) << 8 | bytes[0] as i16;

        // Read the Y value
        let mut bytes = [0u8, 0u8];
        my_i2c.read(ADDRESS, REG_XOUT_LSB + 2, &mut bytes);
        let y = (bytes[1] as i16) << 8 | bytes[0] as i16;

        // Read the Z values
        let mut bytes = [0u8, 0u8];
        my_i2c.read(ADDRESS, REG_XOUT_LSB + 4, &mut bytes);
        let z = (bytes[1] as i16) << 8 | bytes[0] as i16;

        info!("X: {}, Y: {}, Z: {}", x, y, z);

        for _ in 0..800000 {
            cortex_m::asm::nop();
        }
    }
}
