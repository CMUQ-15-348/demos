const FONT_WIDTH: u8 = 8;

//const SSD1306_MAX_X:u8 = 127;
const SSD1306_MAX_Y: u8 = 63;
const SSD1306_ADDRESS: u8 = 0x3C;
const SSD1306_COMMAND_MODE: u8 = 0x80;
const SSD1306_DATA_MODE: u8 = 0x40;
const SSD1306_DISPLAY_OFF_CMD: u8 = 0xAE;
const SSD1306_DISPLAY_ON_CMD: u8 = 0xAF;
//const SSD1306_NORMAL_DISPLAY_CMD: u8 = 0xA6;
//const SSD1306_INVERSE_DISPLAY_CMD: u8 = 0xA7;
//const SSD1306_ACTIVATE_SCROLL_CMD: u8 = 0x2F;
//const SSD1306_DEACTIVATE_SCROLL_CMD: u8 = 0x2E;
//const SSD1306_SET_BRIGHTNESS_CMD: u8 = 0x81;

// Horizontal offset
// My screen is shifted two pixels left for some weird reason
const H_OFFSET: u8 = 0x02;

pub struct SSD1306<'a> {
    i2c: &'a I2C1,
}

impl<'a> SSD1306<'a> {
    pub fn new(i2c: &'a I2C1) -> Self {
        SSD1306 { i2c }
    }

    pub fn init(&self) {
        self.display_off(); //display off
        self.send_command(0xA6); //Set Normal Display (default)
        self.display_off(); //display off
        self.send_command(0xD5); //SETDISPLAYCLOCKDIV
        self.send_command(0x80); // the suggested ratio 0x80
        self.send_command(0xA8); //SSD1306_SETMULTIPLEX
        self.send_command(SSD1306_MAX_Y);
        self.send_command(0xD3); //SETdisplay_offSET
        self.send_command(0x00); //no offset
        self.send_command(0x40 | 0x0); //SETSTARTLINE
        self.send_command(0x8D); //CHARGEPUMP
        self.send_command(0x14);
        self.send_command(0x20); //MEMORYMODE
        self.send_command(0x00); //0x0 act like ks0108
        self.send_command(0xA1); //SEGREMAP   Mirror screen horizontally (A0)
        self.send_command(0xC8); //COMSCANDEC Rotate screen vertically (C0)
        self.send_command(0xDA); //0xDA
        self.send_command(0x12); //COMSCANDEC
        self.send_command(0x81); //SETCONTRAST
        self.send_command(0xCF); //
        self.send_command(0xd9); //SETPRECHARGE
        self.send_command(0xF1);
        self.send_command(0xDB); //SETVCOMDETECT
        self.send_command(0x40);
        self.send_command(0xA4); //DISPLAYALLON_RESUME
        self.send_command(0xA6); //NORMALDISPLAY
        self.clear_display();
        self.send_command(0x2E); //Stop scroll
        self.send_command(0x20); //Set Memory Addressing Mode
        self.send_command(0x00); //Set Memory Addressing Mode ab Horizontal addressing mode
    }

    fn send_command(&self, command: u8) {
        self.i2c
            .write(SSD1306_ADDRESS, SSD1306_COMMAND_MODE, command);
    }

    fn send_data(&self, data: u8) {
        self.i2c.write(SSD1306_ADDRESS, SSD1306_DATA_MODE, data);
    }

    pub fn set_text_xy(&self, row: u8, col: u8) {
        self.send_command(0xB0 + row);
        self.send_command(H_OFFSET + ((FONT_WIDTH * col) & 0x0F));
        self.send_command(0x10 + (((FONT_WIDTH * col) >> 4) & 0x0F));
    }

    pub fn put_char(&self, c: char) {
        let mut ch = c as u8;
        if ch < 32 || ch > 127 {
            ch = ' ' as u8;
        }

        for i in 0..FONT_WIDTH {
            //info!("ch: {}", ch);
            let idx: u16 = (ch - 32) as u16 * FONT_WIDTH as u16 + 2 + i as u16;
            //info!("idx: {}", idx);
            self.send_data(CHAR_MAP[idx as usize]);
        }
    }

    pub fn put_string(&self, s: &str) {
        for c in s.chars() {
            self.put_char(c);
        }
    }

    pub fn put_number(&self, n: i32) -> u8 {
        let mut num = n;
        let mut buf = [' '; 10];
        let mut i = 0;
        let mut f = 0;
        if num < 0 {
            f = 1;
            self.put_char('-');
            num = -num;
        } else if num == 0 {
            f = 1;
            self.put_char('0');
            return f;
        }
        while num > 0 {
            buf[i] = ((num % 10) as u8 + '0' as u8) as char;
            num /= 10;
            i += 1;
        }
        f += i as u8;
        while i > 0 {
            self.put_char(buf[i - 1]);
            i -= 1;
        }
        return f;
    }

    pub fn display_on(&self) {
        self.send_command(SSD1306_DISPLAY_ON_CMD);
    }

    pub fn display_off(&self) {
        self.send_command(SSD1306_DISPLAY_OFF_CMD);
    }

    pub fn clear_display(&self) {
        self.send_command(SSD1306_DISPLAY_OFF_CMD); //display off
        for j in 0..8 {
            self.set_text_xy(j, 0);
            for _ in 0..16 {
                self.put_char(' ');
            }
        }
        self.send_command(SSD1306_DISPLAY_ON_CMD); //display on
        self.set_text_xy(0, 0);
    }

    pub fn clear_line(&self, row: u8) {
        self.set_text_xy(row, 0);
        for _ in 0..16 {
            self.put_char(' ');
        }
    }
}
