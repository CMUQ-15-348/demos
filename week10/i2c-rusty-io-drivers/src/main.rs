fn io_reset() {
    // Reset, then deassert the reset on IO_BANK0
    // See Section 2.14 in the datasheet for details
    set_bits(RESETS_BASE, 1 << 5); // Write 1 to reset
    clear_bits(RESETS_BASE, 1 << 5); // Write 0 to deassert reset

    // Reset, then deassert the reset on PADS_BANK0
    // See Section 2.14 in the datasheet for details
    set_bits(RESETS_BASE, 1 << 8); // Write 1 to reset
    clear_bits(RESETS_BASE, 1 << 8); // Write 0 to deassert reset
}

/*
 * The actual main function.
 */
#[entry]
fn main() -> ! {
    // Initialize the clocks and IO pins
    sys_clock::init_clocks();
    io_reset();

    let sda = pin_io::get_pin(2).unwrap();
    let scl = pin_io::get_pin(3).unwrap();

    let my_i2c = I2C1::new(sda, scl);
    my_i2c.init();

    // Delay for a bit for everything to initialize
    for _ in 0..800000 {
        cortex_m::asm::nop();
    }

    // Initialize the QMC5883L sensor
    let compass = QMC5883L::new(&my_i2c);
    compass.init();

    // Initialize the display
    let display = SSD1306::new(&my_i2c);
    display.init();

    loop {
        // Wait for the sensor to signal ready
        loop {
            if compass.data_available() {
                break;
            }
            // Minor wait
            for _ in 0..8000 {
                cortex_m::asm::nop();
            }
        }

        let (x, y, z) = compass.read();

        info!("X: {}, Y: {}, Z: {}", x, y, z);

        for i in 1..4 {
            display.clear_line(i);
        }

        display.set_text_xy(0, 0);
        display.put_string("Data Ready:");
        display.set_text_xy(1, 0);
        display.put_string("X: ");
        display.put_number(x as i32);
        display.set_text_xy(2, 0);
        display.put_string("Y: ");
        display.put_number(y.into());
        display.set_text_xy(3, 0);
        display.put_string("Z: ");
        display.put_number(z.into());

        for _ in 0..800000 {
            cortex_m::asm::nop();
        }
    }
}
